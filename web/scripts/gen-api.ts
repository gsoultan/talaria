// Writes src/gen/api.ts from the API's OpenAPI document (api/openapi.json,
// written by `talaria openapi` from the kakarot service). It turns kakarot's
// JSON Schema subset into TypeScript interfaces, and each operation into an
// entry of Ops (its input and output types) and ops (its method, path and
// parameters), so the client calls operations by name with checked types.
//
//   bun run scripts/gen-api.ts ../api/openapi.json src/gen/api.ts

type Schema = {
  $ref?: string
  type?: string | string[]
  format?: string
  properties?: Record<string, Schema>
  required?: string[]
  items?: Schema
  additionalProperties?: Schema
}
type Param = { name: string; in: 'path' | 'query' | 'header'; required?: boolean; schema: Schema }
type Operation = {
  operationId: string
  parameters?: Param[]
  requestBody?: { content: Record<string, { schema: Schema }> }
  responses: Record<string, { content?: Record<string, { schema: Schema }> }>
}
type Doc = { paths: Record<string, Record<string, Operation>>; components: { schemas: Record<string, Schema> } }

export {}

const [src, out] = process.argv.slice(2) as [string, string]
const doc: Doc = await Bun.file(src).json()

const refName = (ref: string) => ref.replace('#/components/schemas/', '')
const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k))

function ts(s: Schema, indent = ''): string {
  if (s.$ref) return refName(s.$ref)
  const types = Array.isArray(s.type) ? s.type : [s.type]
  const nullable = types.includes('null')
  const t = types.find((x) => x && x !== 'null')
  let body: string
  switch (t) {
    case 'string':
      body = 'string'
      break
    case 'integer':
    case 'number':
      body = 'number'
      break
    case 'boolean':
      body = 'boolean'
      break
    case 'array':
      body = `${wrap(ts(s.items ?? {}, indent))}[]`
      break
    case 'object':
      if (s.additionalProperties) body = `Record<string, ${ts(s.additionalProperties, indent)}>`
      else body = object(s, indent)
      break
    default:
      body = 'unknown'
  }
  return nullable ? `${body} | null` : body
}

const wrap = (t: string) => (/[|&]/.test(t) ? `(${t})` : t)

function object(s: Schema, indent: string): string {
  const props = Object.entries(s.properties ?? {}).sort(([a], [b]) => a.localeCompare(b))
  if (props.length === 0) return 'Record<string, never>'
  const req = new Set(s.required ?? [])
  const inner = indent + '  '
  return `{\n${props.map(([k, v]) => `${inner}${key(k)}${req.has(k) ? '' : '?'}: ${ts(v, inner)}`).join('\n')}\n${indent}}`
}

const lines: string[] = [
  '// Copyright (c) 2026 Gembit Soultan Shirazi <gembit.soultan@gmail.com>. All rights reserved.',
  '// SPDX-License-Identifier: MIT',
  '',
  '// Code generated by scripts/gen-api.ts from api/openapi.json. DO NOT EDIT.',
  '',
]

for (const [name, s] of Object.entries(doc.components.schemas).sort(([a], [b]) => a.localeCompare(b))) {
  if (name === 'errorBody') continue
  lines.push(`export type ${name} = ${ts(s)}`, '')
}

type Entry = { id: string; method: string; path: string; pathParams: string[]; query: string[]; body: boolean; input: string; output: string; stream: boolean }
const entries: Entry[] = []
for (const [path, methods] of Object.entries(doc.paths)) {
  for (const [method, op] of Object.entries(methods)) {
    const params = (op.parameters ?? []).filter((p) => p.in !== 'header')
    const parts: string[] = []
    const fields = params.map((p) => `${key(p.name)}${p.in === 'path' ? '' : '?'}: ${ts(p.schema)}`)
    if (fields.length) parts.push(`{ ${fields.join('; ')} }`)
    const body = op.requestBody ? Object.values(op.requestBody.content)[0]!.schema : undefined
    if (body) parts.push(ts(body))
    const ok = Object.entries(op.responses).find(([code]) => code.startsWith('2'))![1]
    const content = ok.content ?? {}
    const stream = 'text/event-stream' in content
    const resp = Object.values(content)[0]?.schema
    entries.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path,
      pathParams: params.filter((p) => p.in === 'path').map((p) => p.name),
      query: params.filter((p) => p.in === 'query').map((p) => p.name),
      body: !!body,
      input: parts.length ? parts.join(' & ') : 'Record<string, never>',
      output: resp ? ts(resp) : 'void',
      stream,
    })
  }
}
entries.sort((a, b) => a.id.localeCompare(b.id))

lines.push('/** Every operation: what it takes and what it returns. */', 'export interface Ops {')
for (const e of entries) lines.push(`  ${JSON.stringify(e.id)}: { input: ${e.input}; output: ${e.output} }`)
lines.push('}', '')
lines.push('/** How each operation travels: method, path, and which input fields go in the path and query. */')
lines.push('export const ops = {')
for (const e of entries) {
  lines.push(
    `  ${JSON.stringify(e.id)}: { method: '${e.method}', path: '${e.path}', pathParams: ${JSON.stringify(e.pathParams)}, query: ${JSON.stringify(e.query)}, body: ${e.body}, stream: ${e.stream} },`,
  )
}
lines.push('} as const', '', 'export type OpName = keyof Ops', '')

await Bun.write(out, lines.join('\n'))
console.log(`${out}: ${Object.keys(doc.components.schemas).length - 1} types, ${entries.length} operations`)
